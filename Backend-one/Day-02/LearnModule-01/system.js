// Export lnline Using export 
// exports is just a shorthand reference to module.exports. You can add properties one by one —
exports.addition = function(a,b){
    return a + b ;
}
exports.substraction = function(a,b){
    return a - b ;
}
exports.multiplication = function(a,b){
    return a * b ; 
}
exports.divsion = function(a,b){
    return a / b ; 
}